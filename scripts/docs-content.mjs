import { readdirSync, readFileSync, writeFileSync } from "node:fs";

// What /docs serves: the README, the licence and every topic in docs/. The Worker has no repository
// to read them from, so they are carried into it as a module. It is the app's generate script, which
// platform generate runs first on every install, dev and deploy, and typecheck and test run it too,
// so the module is generated, never committed.
const root = new URL("../", import.meta.url);
const read = (file) => readFileSync(new URL(file, root), "utf8");

const topics = readdirSync(new URL("docs/", root))
  .filter((file) => file.endsWith(".md"))
  .sort()
  .map((file) => ({ slug: file.replace(/\.md$/, ""), source: read(`docs/${file}`) }));

writeFileSync(
  new URL("src/docs/content.ts", root),
  `// Generated by scripts/docs-content.mjs from README.md, LICENSE.md and docs/*.md. Do not edit.
export const README_MD: string = ${JSON.stringify(read("README.md"))};
export const LICENSE_MD: string = ${JSON.stringify(read("LICENSE.md"))};
export const TOPIC_SOURCES: { slug: string; source: string }[] = ${JSON.stringify(topics, null, 2)};
`,
);
